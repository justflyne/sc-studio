"""Build a self-starting classic-JS payload and a C header for custom Gadget.

The emitted JavaScript has no imports and targets the supplied Android agent.
No APK, Gadget binary or external config is generated by this builder.
"""
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULES = HERE / "embedded-deps"


def build_payload() -> bytes:
    vendor = (MODULES / "vendor/tweetnacl.mjs").read_text()
    if vendor.count("export default require_nacl_fast();") != 1:
        raise ValueError("Unexpected TweetNaCl module format")
    vendor = vendor.replace("export default require_nacl_fast();", "return require_nacl_fast();")
    crypto = (MODULES / "remote/RemoteCrypto.js").read_text()
    crypto = re.sub(r"^export (?=function )", "", crypto, flags=re.MULTILINE)
    loader = (HERE / "loader.js").read_text()
    loader = re.sub(r"^import .*;\n", "", loader, flags=re.MULTILINE)
    if re.search(r"^\s*(import|export)\s", loader + crypto + vendor, flags=re.MULTILINE):
        raise ValueError("Unresolved ES module declaration")
    source = (
        '"use strict";\n'
        '// Self-starting Android payload for embedding in a custom Frida Gadget.\n'
        '// Generated by build_embedded.py; edit loader.js and rebuild.\n'
        '(() => {\n'
        'const nacl = (() => {\n' + vendor + '\n})();\n'
        + crypto + '\n'
        '// This Android agent uses native Frida APIs; these optional globals\n'
        '// are supplied if the custom runtime already includes language bridges.\n'
        'const ObjCBridge = globalThis.ObjC;\n'
        'const JavaBridge = globalThis.Java;\n'
        + loader + '\n'
        '// Begin on script load; a later Gadget init() awaits the same Promise.\n'
        'void initLoader("embedded", {});\n'
        '})();\n'
    )
    return source.encode("utf-8")


def make_header(payload: bytes) -> str:
    data = payload + b"\0"
    lines = [
        "/* Generated by build_embedded.py. UTF-8 JavaScript followed by NUL. */",
        "#ifndef BTB_EMBEDDED_SCRIPT_H",
        "#define BTB_EMBEDDED_SCRIPT_H",
        "#include <stddef.h>",
        "static const unsigned char btb_embedded_script[] = {",
    ]
    for offset in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 20]) + ",")
    lines.extend([
        "};",
        "static const size_t btb_embedded_script_length = sizeof(btb_embedded_script) - 1;",
        "static inline const char *btb_get_embedded_script(void) {",
        "  return (const char *)btb_embedded_script;",
        "}",
        "#endif",
        "",
    ])
    return "\n".join(lines)


if __name__ == "__main__":
    payload = build_payload()
    (HERE / "embedded-loader.js").write_bytes(payload)
    (HERE / "embedded-script.h").write_text(make_header(payload))
    metadata = {
        "javascript": "embedded-loader.js",
        "header": "embedded-script.h",
        "bytes": len(payload),
        "sha256": hashlib.sha256(payload).hexdigest(),
        "format": "self-starting classic JavaScript; no imports or external files",
        "target": "Android; current native-API agent from /v1/script",
        "header_encoding": "UTF-8 byte array, NUL-terminated",
    }
    (HERE / "embedded-info.json").write_text(json.dumps(metadata, indent=2))
    print(f"Built embedded-loader.js ({len(payload)} bytes) and embedded-script.h")
